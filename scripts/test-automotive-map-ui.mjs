import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const [packageText, mapUi, mapCss, mapTheme, homepageMap, homepageCanvas, homepageMapCss, landing, nextConfig, websiteHeader, mapPage, greekMapPage, workerCopy] = await Promise.all([
  readFile("package.json", "utf8"),
  readFile("src/components/map/AutomotiveMap.tsx", "utf8"),
  readFile("src/components/map/AutomotiveMap.module.css", "utf8"),
  readFile("src/lib/noxaMapTheme.ts", "utf8"),
  readFile("src/components/map/HomepageMapPreview.tsx", "utf8"),
  readFile("src/components/map/HomepageMapCanvas.tsx", "utf8"),
  readFile("src/components/map/HomepageMapPreview.module.css", "utf8"),
  readFile("src/components/culture/CultureLandingV2.tsx", "utf8"),
  readFile("next.config.ts", "utf8"),
  readFile("src/components/navigation/WebsiteHeader.tsx", "utf8"),
  readFile("src/app/map/page.tsx", "utf8"),
  readFile("src/app/el/map/page.tsx", "utf8"),
  readFile("scripts/copy-maplibre-worker.mjs", "utf8"),
]);

const packageJson = JSON.parse(packageText);
assert.equal(packageJson.dependencies["maplibre-gl"], "6.8.0", "MapLibre must stay pinned to the patched v6 release");
assert.equal(packageJson.scripts.prebuild, "node scripts/copy-maplibre-worker.mjs", "production build must self-host the MapLibre worker");
assert.equal(packageJson.scripts.predev, "node scripts/copy-maplibre-worker.mjs", "development must self-host the same MapLibre worker");
for (const source of [mapUi, homepageCanvas]) {
  assert.ok(source.includes('setWorkerUrl("/maplibre/maplibre-gl-worker.mjs")'), "every MapLibre map entrypoint must use the self-hosted ESM worker");
  assert.ok(!source.includes("module.default") && !source.includes("Module.default"), "MapLibre v6 entrypoints must not rely on the removed default export");
}
assert.ok(!mapUi.includes("maplibreModule.default"), "MapLibre Marker must use the v6 ESM export");
assert.ok(workerCopy.includes('"maplibre-gl-worker.mjs"') && workerCopy.includes('"maplibre-gl-shared.mjs"'), "worker and shared ESM modules must be copied side-by-side");
assert.ok(workerCopy.includes('"public", "maplibre"'), "MapLibre worker must be served from NOXA public assets");

for (const required of [
  "/api/map/features?bbox=",
  "cluster: true",
  "navigator.geolocation",
  '"events"',
  '"tracks"',
  '"routes"',
  '"places"',
  "moveend",
  "applyNoxaBasemapTheme",
  "createNoxaPoiImage",
  "queryRenderedFeatures",
]) {
  assert.ok(mapUi.includes(required), `AutomotiveMap must include ${required}`);
}

assert.ok(!mapUi.includes("cooperativeGestures: true"), "mobile map must pan naturally with one finger");
assert.ok(mapTheme.includes("#181b20"), "NOXA basemap must visibly separate land from sea");
assert.ok(mapTheme.includes("ROAD_MAJOR"), "NOXA basemap must preserve a strong road hierarchy");
assert.ok(!mapTheme.includes("const firstFill"), "NOXA theme must never recolor an arbitrary first fill layer");
assert.ok(mapTheme.includes("createNoxaPoiImage"), "custom automotive POI icons must be generated by NOXA");
assert.ok(mapTheme.includes("map.setMaxBounds(null)"), "interactive NOXA Map must allow navigation outside Greece");
assert.ok(mapUi.includes("center: target.center"), "global map must use the validated deep-link target");
assert.ok(mapUi.includes("latitudeParam === null ? Number.NaN"), "missing deep-link coordinates must never become 0,0");
assert.ok(mapUi.includes("localizedEventHref"), "map event links must preserve EN/EL locale");
assert.ok(mapUi.includes('map.addSource("noxa-selected-point"'), "selected markers must use a dedicated visual source");
assert.ok(mapUi.includes('id: "noxa-selected-ring"'), "selected point must gain an obvious high-contrast ring");
assert.ok(mapCss.includes(".main :global(.maplibregl-ctrl-group)"), "map controls must have dedicated responsive treatment");
assert.ok(mapCss.includes("detailSheetExpanded"), "mobile detail bottom sheet styles must exist");
assert.ok(mapCss.includes("@media (max-width: 900px)"), "map must have a dedicated mobile layout");
assert.ok(!mapCss.includes("overlow-y"), "mobile detail sheet scrolling must not regress to the misspelled overflow property");
assert.ok(mapCss.includes("overflow-y: auto; overscroll-behavior: contain;"), "expanded mobile detail sheet must scroll independently");
assert.ok(mapCss.includes(".layerChip, .layerChipActive { min-height: 44px;"), "mobile map layer controls must keep a 44px touch target");
assert.ok(mapCss.includes("bottom: max(7px, env(safe-area-inset-bottom))"), "mobile detail sheet must respect the iPhone safe area");
assert.ok(mapCss.includes(".searchBox input { font-size: 16px; }"), "mobile map search must avoid iOS focus zoom");
assert.ok(mapCss.includes(".sourceAction"), "source action must stay visually secondary to View Event and Directions");
assert.ok(homepageMap.includes("Open NOXA Map"), "homepage must expose the full automotive map CTA");
for (const glyph of ["⚑", "⌁", "⌖"]) assert.ok(!homepageMap.includes(glyph), `homepage map preview must not use ${glyph} as a POI icon`);
assert.ok(homepageMapCss.includes("61svh"), "homepage map preview must have a strong mobile visual presence");
assert.ok(landing.includes("<HomepageMapPreview locale={locale} />"), "homepage map preview must sit after Radar discovery");

assert.ok(nextConfig.includes("https://tiles.openfreemap.org"), "CSP must allow the OpenFreeMap tile host");
assert.ok(nextConfig.includes("geolocation=(self)"), "geolocation must be restricted to NOXA itself");
assert.ok(websiteHeader.includes('["Map", `${base}/map`]'), "website navigation must expose the Map route");
assert.ok(mapPage.includes('<AutomotiveMap locale="en" />'), "English map route must render the map");
assert.ok(greekMapPage.includes('<AutomotiveMap locale="el" />'), "Greek map route must render the localized map");

assert.ok(mapUi.includes("getClusterExpansionZoom"), "clusters must expand to the MapLibre-calculated zoom level");
assert.ok(mapUi.includes('"icon-allow-overlap": false'), "POI icons must avoid overlap at high density");
assert.ok(mapUi.includes("payload.meta.capped"), "map must surface viewport result caps instead of silently truncating");
assert.ok(mapUi.includes("const statusText = activeLayers.size === 0"), "map must distinguish disabled layers from a genuinely empty area");
assert.ok(mapUi.includes("statusText ? <div"), "normal map state must not keep a permanent status pill visible");
assert.ok(mapUi.includes("capped"), "map must tell the user to zoom in when the viewport is capped");
assert.ok(mapUi.includes("{selected ? <aside"), "detail sheet must only exist after the user selects a map object");

assert.ok(mapUi.includes("searchResults"), "map search must expose visible-area results");
assert.ok(mapUi.includes("focusFeature"), "search result selection must focus a map feature");
assert.ok(mapUi.includes("geometryBounds"), "route/shape search results must fit their full geometry");
assert.ok(mapUi.includes("map.fitBounds"), "shape selection must zoom to the selected route or area");
assert.ok(mapUi.includes('event.key !== "Escape"'), "desktop Escape must close search/details state");
assert.ok(mapCss.includes(".searchResults"), "search-result panel styles must exist");

console.log("Automotive map UI fixture: PASS");
